/**
 * Bash installer served to a new VPS by the panel (see routes/nodeEnroll.ts).
 * Every value interpolated into the script is validated/sanitised by the caller; only [A-Za-z0-9 ._:/@-] reach the shell.
 *
 * Works on normal VPS (systemd + Docker) and on containers / sandboxes without systemd, Docker or root
 * (background supervisor, local runtime, private Node.js, automatic Cloudflare quick tunnel when the panel cannot reach the node).
 */
export interface ScriptInput {
  panelUrl: string;
  enrollToken: string;
  nodeToken: string;
  port: number;
  domain?: string;
  name: string;
}

const safe = (v: string) => String(v).replace(/[^A-Za-z0-9 ._:/@-]/g, "");

export function buildInstallScript(i: ScriptInput): string {
  const panel = safe(i.panelUrl);
  const name = safe(i.name) || "node";
  const domain = safe(i.domain || "");
  return `#!/usr/bin/env bash
# Verse Node installer — adds this machine to your panel as "${name}".
# Works on normal VPS (systemd) AND on containers / sandboxes without systemd, Docker or root.
# Generated by ${panel}. Safe to run again (it updates the node and keeps its servers).
set -o pipefail

PANEL_URL="${panel}"
ENROLL_TOKEN="${safe(i.enrollToken)}"
NODE_TOKEN="${safe(i.nodeToken)}"
NODE_PORT="${Number(i.port) || 6870}"
NODE_DOMAIN="${domain}"
NODE_NAME="${name}"
SERVICE="verse-node"

c() { printf '\\033[1;36m[verse-node]\\033[0m %s\\n' "$*"; }
ok() { printf '\\033[1;32m[ok]\\033[0m %s\\n' "$*"; }
warn() { printf '\\033[1;33m[warn]\\033[0m %s\\n' "$*"; }
fail() { printf '\\033[1;31m[error]\\033[0m %s\\n' "$*" >&2; exit 1; }

[ "$(uname -s)" = "Linux" ] || fail "Linux only."

# ---------- what kind of machine is this? ----------
IS_ROOT=0; [ "$(id -u)" -eq 0 ] && IS_ROOT=1
SUDO=""
if [ "$IS_ROOT" -eq 0 ] && command -v sudo >/dev/null 2>&1 && sudo -n true >/dev/null 2>&1; then SUDO="sudo"; fi
CAN_PKG=0; if [ "$IS_ROOT" -eq 1 ] || [ -n "$SUDO" ]; then CAN_PKG=1; fi

HAS_SYSTEMD=0
if [ "$IS_ROOT" -eq 1 ] && [ -d /run/systemd/system ] && command -v systemctl >/dev/null 2>&1; then HAS_SYSTEMD=1; fi

if [ -n "$VERSE_NODE_DIR" ]; then INSTALL_DIR="$VERSE_NODE_DIR"
elif [ "$IS_ROOT" -eq 1 ]; then INSTALL_DIR="/opt/verse-node"
else INSTALL_DIR="$HOME/verse-node"; fi
mkdir -p "$INSTALL_DIR" 2>/dev/null || fail "Cannot create $INSTALL_DIR (set VERSE_NODE_DIR to a writable folder)."

PM=""
if command -v apt-get >/dev/null 2>&1; then PM="apt"; elif command -v dnf >/dev/null 2>&1; then PM="dnf"; elif command -v yum >/dev/null 2>&1; then PM="yum"; fi

pkg_install() {
  [ "$CAN_PKG" -eq 1 ] && [ -n "$PM" ] || return 1
  case "$PM" in
    apt) DEBIAN_FRONTEND=noninteractive $SUDO apt-get install -y "$@" >/dev/null 2>&1 ;;
    dnf) $SUDO dnf install -y "$@" >/dev/null 2>&1 ;;
    yum) $SUDO yum install -y "$@" >/dev/null 2>&1 ;;
  esac
}

if [ "$HAS_SYSTEMD" -eq 1 ]; then c "Mode: systemd service"; else c "Mode: no systemd (container / sandbox) — the node will run as a background process"; fi
c "Installing node \\"$NODE_NAME\\" into $INSTALL_DIR ..."
[ "$PM" = "apt" ] && [ "$CAN_PKG" -eq 1 ] && $SUDO apt-get update -y >/dev/null 2>&1
for t in curl tar gzip; do
  command -v "$t" >/dev/null 2>&1 || pkg_install "$t" ca-certificates || true
  command -v "$t" >/dev/null 2>&1 || fail "'$t' is required but missing and could not be installed."
done

# ---------- Node.js >= 20 ----------
node_ok() { command -v node >/dev/null 2>&1 && [ "$(node -v | tr -d v | cut -d. -f1)" -ge 20 ] 2>/dev/null; }
install_portable_node() {
  local A NA V
  A="$(uname -m)"
  case "$A" in x86_64|amd64) NA="x64" ;; aarch64|arm64) NA="arm64" ;; armv7l) NA="armv7l" ;; *) return 1 ;; esac
  V="v22.11.0"
  c "Downloading a private copy of Node.js $V (no root needed) ..."
  mkdir -p "$INSTALL_DIR/runtime" && curl -fsSL "https://nodejs.org/dist/$V/node-$V-linux-$NA.tar.gz" | tar -xz -C "$INSTALL_DIR/runtime" --strip-components=1 || return 1
  export PATH="$INSTALL_DIR/runtime/bin:$PATH"
}
if ! node_ok; then
  if [ "$CAN_PKG" -eq 1 ] && [ -n "$PM" ]; then
    c "Installing Node.js 22 ..."
    if [ "$PM" = "apt" ]; then curl -fsSL https://deb.nodesource.com/setup_22.x | \${SUDO:+$SUDO -E} bash - >/dev/null 2>&1
    else curl -fsSL https://rpm.nodesource.com/setup_22.x | \${SUDO:+$SUDO -E} bash - >/dev/null 2>&1; fi
    pkg_install nodejs
  fi
  node_ok || install_portable_node
  node_ok || fail "Could not install Node.js 20+ (needs x86_64/arm64 Linux with glibc)."
fi
command -v npm >/dev/null 2>&1 || fail "npm is missing."
NODE_DIR="$(dirname "$(command -v node)")"
ok "Node.js $(node -v)"

# ---------- Docker (optional) ----------
USE_DOCKER=0
if command -v docker >/dev/null 2>&1 && docker info >/dev/null 2>&1; then
  USE_DOCKER=1
elif [ "$HAS_SYSTEMD" -eq 1 ] && [ "$CAN_PKG" -eq 1 ]; then
  if ! command -v docker >/dev/null 2>&1; then
    c "Installing Docker (takes a minute) ..."
    curl -fsSL https://get.docker.com | sh >/dev/null 2>&1 || warn "Docker installation failed."
  fi
  systemctl enable --now docker >/dev/null 2>&1 || true
  sleep 2
  docker info >/dev/null 2>&1 && USE_DOCKER=1
fi
if [ "$USE_DOCKER" -eq 1 ]; then ok "Docker is running"; else warn "Docker is not available here — servers will run directly on this machine (local mode: no container isolation, no RAM limit)."; fi

# ---------- download the node ----------
c "Downloading node files from your panel ..."
TMP="$(mktemp "\${TMPDIR:-/tmp}/verse-node.XXXXXX")"
HTTP=$(curl -sS -o "$TMP" -w '%{http_code}' "$PANEL_URL/api/nodes/enroll/$ENROLL_TOKEN/package.tgz") || fail "Cannot reach the panel at $PANEL_URL from this machine."
[ "$HTTP" = "200" ] || fail "Panel refused the download (HTTP $HTTP). The link may have expired — create a new one in Nodes → Add VPS."

if [ "$HAS_SYSTEMD" -eq 1 ]; then systemctl stop "$SERVICE" >/dev/null 2>&1 || true
elif [ -x "$INSTALL_DIR/stop.sh" ]; then "$INSTALL_DIR/stop.sh" >/dev/null 2>&1 || true; fi
tar -xzf "$TMP" -C "$INSTALL_DIR" || fail "Could not unpack the node files."
rm -f "$TMP"

c "Installing dependencies (this can take a few minutes) ..."
NPMLOG="$INSTALL_DIR/npm-install.log"
( cd "$INSTALL_DIR" && npm install --omit=dev --no-audit --no-fund --legacy-peer-deps >"$NPMLOG" 2>&1 ) || { tail -n 15 "$NPMLOG"; fail "npm install failed (log above)."; }
# 'vite' is listed as a dev dependency in some panel builds but the server bundle needs it at runtime
( cd "$INSTALL_DIR" && node -e "require.resolve('vite')" >/dev/null 2>&1 ) || {
  c "Adding runtime module: vite ..."
  ( cd "$INSTALL_DIR" && npm install vite --no-audit --no-fund --legacy-peer-deps >>"$NPMLOG" 2>&1 ) || warn "Could not install vite (see $NPMLOG)."
}
ok "Dependencies installed"

# ---------- config ----------
umask 077
cat > "$INSTALL_DIR/.env" <<ENVEOF
NODE_ENV=production
NODE_MODE=true
NODE_TOKEN=$NODE_TOKEN
PORT=$NODE_PORT
PANEL_URL=$PANEL_URL
ENVEOF
umask 022

# no Docker -> run game servers as plain processes
if [ "$USE_DOCKER" -eq 0 ]; then
  mkdir -p "$INSTALL_DIR/.data"
  ( cd "$INSTALL_DIR" && node -e '
    const fs=require("fs"),p=".data/settings.json";let s={};
    try{s=JSON.parse(fs.readFileSync(p,"utf8"))}catch(e){}
    s.defaultRuntime="local";fs.writeFileSync(p,JSON.stringify(s,null,2));' ) && ok "Runtime set to local (no Docker)"
fi

# ---------- start / stop helpers ----------
write_helpers() {
  cat > "$INSTALL_DIR/run.sh" <<RUNEOF
#!/usr/bin/env bash
cd "$INSTALL_DIR" || exit 1
export PATH="$NODE_DIR:\\$PATH"
set -a; . ./.env; set +a
echo \\$\\$ > supervisor.pid
while true; do
  node dist/server.cjs >> node.log 2>&1 &
  echo \\$! > node.pid
  wait \\$!
  sleep 5
done
RUNEOF
  cat > "$INSTALL_DIR/tunnel.sh" <<TUNEOF
#!/usr/bin/env bash
cd "$INSTALL_DIR" || exit 1
set -a; . ./.env; set +a
echo \\$\\$ > tunnel-supervisor.pid
while true; do
  rm -f tunnel.log
  ./bin/cloudflared tunnel --no-autoupdate --protocol http2 --url "http://127.0.0.1:\\$PORT" > tunnel.log 2>&1 &
  echo \\$! > tunnel.pid
  URL=""
  for i in \\$(seq 1 40); do
    URL="\\$(grep -o 'https://[a-z0-9-]*\\.trycloudflare\\.com' tunnel.log 2>/dev/null | head -n1)"
    [ -n "\\$URL" ] && break
    sleep 1.5
  done
  if [ -n "\\$URL" ] && [ -n "\\$NODE_ID" ]; then
    for j in 1 2 3 4 5; do
      CODE="\\$(curl -s -m 25 -o /dev/null -w '%{http_code}' -X POST -H 'Content-Type: application/json' -d "{\\"nodeId\\":\\"\\$NODE_ID\\",\\"token\\":\\"\\$NODE_TOKEN\\",\\"host\\":\\"\\\${URL#https://}\\"}" "\\$PANEL_URL/api/nodes/enroll/address")"
      [ "\\$CODE" = "200" ] && break
      sleep 6
    done
  fi
  wait \\$(cat tunnel.pid)
  sleep 5
done
TUNEOF
  cat > "$INSTALL_DIR/start.sh" <<STEOF
#!/usr/bin/env bash
cd "$INSTALL_DIR" || exit 1
alive() { [ -f "\\$1" ] && kill -0 "\\$(cat "\\$1")" 2>/dev/null; }
alive supervisor.pid || { if command -v setsid >/dev/null 2>&1; then setsid nohup ./run.sh >/dev/null 2>&1 < /dev/null & else nohup ./run.sh >/dev/null 2>&1 < /dev/null & fi; }
if [ -x ./bin/cloudflared ] && [ -f ./tunnel.enabled ]; then
  alive tunnel-supervisor.pid || { if command -v setsid >/dev/null 2>&1; then setsid nohup ./tunnel.sh >/dev/null 2>&1 < /dev/null & else nohup ./tunnel.sh >/dev/null 2>&1 < /dev/null & fi; }
fi
STEOF
  cat > "$INSTALL_DIR/stop.sh" <<SPEOF
#!/usr/bin/env bash
cd "$INSTALL_DIR" || exit 1
for f in supervisor.pid tunnel-supervisor.pid node.pid tunnel.pid; do
  [ -f "\\$f" ] && kill "\\$(cat "\\$f")" 2>/dev/null
  rm -f "\\$f"
done
SPEOF
  chmod +x "$INSTALL_DIR"/run.sh "$INSTALL_DIR"/tunnel.sh "$INSTALL_DIR"/start.sh "$INSTALL_DIR"/stop.sh
}

start_node() {
  if [ "$HAS_SYSTEMD" -eq 1 ]; then
    cat > "/etc/systemd/system/$SERVICE.service" <<UNITEOF
[Unit]
Description=Verse Node ($NODE_NAME)
After=network-online.target docker.service
Wants=network-online.target

[Service]
WorkingDirectory=$INSTALL_DIR
EnvironmentFile=$INSTALL_DIR/.env
ExecStart=$(command -v node) dist/server.cjs
Restart=always
RestartSec=5
User=root

[Install]
WantedBy=multi-user.target
UNITEOF
    systemctl daemon-reload
    systemctl enable "$SERVICE" >/dev/null 2>&1
    systemctl restart "$SERVICE"
  else
    write_helpers
    "$INSTALL_DIR/stop.sh" >/dev/null 2>&1
    sleep 1
    "$INSTALL_DIR/start.sh"
  fi
}

wait_node() {
  UP=0
  for _ in $(seq 1 40); do
    if curl -fs "http://127.0.0.1:$NODE_PORT/" >/dev/null 2>&1; then UP=1; break; fi
    sleep 1.5
  done
}

c "Starting the node ..."
start_node
c "Waiting for the node to start ..."
wait_node

# self-heal: install any package the bundle says is missing, then retry
if [ "$UP" -eq 0 ] && [ "$HAS_SYSTEMD" -eq 0 ]; then
  for _ in 1 2 3 4 5; do
    MISSING="$(grep -o "Cannot find module '[^']*'" "$INSTALL_DIR/node.log" 2>/dev/null | tail -n1 | sed "s/Cannot find module '//; s/'$//")"
    case "$MISSING" in ""|.*|/*) break ;; esac
    c "Installing missing module: $MISSING ..."
    ( cd "$INSTALL_DIR" && npm install "$MISSING" --no-audit --no-fund --legacy-peer-deps >>"$NPMLOG" 2>&1 ) || break
    "$INSTALL_DIR/stop.sh" >/dev/null 2>&1; : > "$INSTALL_DIR/node.log"; "$INSTALL_DIR/start.sh"
    wait_node
    [ "$UP" -eq 1 ] && break
  done
fi
if [ "$UP" -ne 1 ]; then
  if [ "$HAS_SYSTEMD" -eq 1 ]; then journalctl -u "$SERVICE" -n 25 --no-pager; else tail -n 25 "$INSTALL_DIR/node.log" 2>/dev/null; fi
  fail "The node did not start (log above)."
fi
ok "Node is running on port $NODE_PORT"

# ---------- firewall ----------
if command -v ufw >/dev/null 2>&1 && ufw status 2>/dev/null | grep -q "Status: active"; then
  ufw allow "$NODE_PORT/tcp" >/dev/null 2>&1 && ok "ufw: opened $NODE_PORT/tcp"
fi

# ---------- public address / optional HTTPS ----------
PUBLIC_IP=""
for u in https://api.ipify.org https://ifconfig.me/ip https://icanhazip.com; do
  PUBLIC_IP="$(curl -fs -m 5 "$u" 2>/dev/null | tr -d '[:space:]')"
  case "$PUBLIC_IP" in [0-9]*.[0-9]*.[0-9]*.[0-9]*) break ;; *) PUBLIC_IP="" ;; esac
done

ENROLL_PORT="$NODE_PORT"
ENROLL_SSL="false"
ENROLL_HOST="$PUBLIC_IP"
ENROLL_TUNNEL="false"

if [ -n "$NODE_DOMAIN" ] && [ "$HAS_SYSTEMD" -eq 1 ]; then
  c "Checking DNS for $NODE_DOMAIN ..."
  RESOLVED="$(getent ahostsv4 "$NODE_DOMAIN" 2>/dev/null | awk '{print $1}' | sort -u | tr '\\n' ' ')"
  if [ -n "$PUBLIC_IP" ] && echo " $RESOLVED " | grep -q " $PUBLIC_IP "; then
    ok "$NODE_DOMAIN points to this VPS ($PUBLIC_IP)"
    if ! command -v caddy >/dev/null 2>&1; then
      c "Installing Caddy for HTTPS ..."
      if [ "$PM" = "apt" ]; then
        pkg_install debian-keyring debian-archive-keyring apt-transport-https gpg
        curl -1sLf 'https://dl.cloudsmith.io/public/caddy/stable/gpg.key' | gpg --dearmor --yes -o /usr/share/keyrings/caddy-stable-archive-keyring.gpg
        curl -1sLf 'https://dl.cloudsmith.io/public/caddy/stable/debian.deb.txt' > /etc/apt/sources.list.d/caddy-stable.list
        apt-get update -y >/dev/null 2>&1; pkg_install caddy
      else
        dnf install -y 'dnf-command(copr)' >/dev/null 2>&1 && dnf copr enable -y @caddy/caddy >/dev/null 2>&1 && pkg_install caddy
      fi
    fi
    if command -v caddy >/dev/null 2>&1; then
      mkdir -p /etc/caddy
      printf '%s {\\n    reverse_proxy 127.0.0.1:%s\\n}\\n' "$NODE_DOMAIN" "$NODE_PORT" > /etc/caddy/Caddyfile
      systemctl enable --now caddy >/dev/null 2>&1; systemctl reload caddy >/dev/null 2>&1 || systemctl restart caddy >/dev/null 2>&1
      command -v ufw >/dev/null 2>&1 && ufw status 2>/dev/null | grep -q "Status: active" && { ufw allow 80/tcp >/dev/null 2>&1; ufw allow 443/tcp >/dev/null 2>&1; }
      ENROLL_PORT="443"; ENROLL_SSL="true"; ENROLL_HOST="$NODE_DOMAIN"
      ok "HTTPS is set up on https://$NODE_DOMAIN"
    else
      warn "Could not install Caddy — continuing without HTTPS (plain http on port $NODE_PORT)."
    fi
  else
    warn "$NODE_DOMAIN does not point to this VPS (\${RESOLVED:-no A record}; this VPS is \${PUBLIC_IP:-unknown}). Continuing without HTTPS."
    warn "Fix the A record later and run this command again to enable HTTPS."
  fi
fi

# ---------- tell the panel ----------
enroll_call() {
  BODY=$(printf '{"port":%s,"ssl":%s,"host":"%s","tunnel":%s}' "$ENROLL_PORT" "$ENROLL_SSL" "$ENROLL_HOST" "$ENROLL_TUNNEL")
  RESP="$(curl -sS -m 45 -X POST -H 'Content-Type: application/json' -d "$BODY" -w '\\n%{http_code}' "$PANEL_URL/api/nodes/enroll/$ENROLL_TOKEN" 2>&1)"
  CODE="$(printf '%s' "$RESP" | tail -n1)"
  MSG="$(printf '%s' "$RESP" | sed '$d' | sed -n 's/.*"error":"\\([^"]*\\)".*/\\1/p')"
}

# the panel cannot reach this machine directly (container behind NAT, closed firewall): use a free Cloudflare quick tunnel
setup_tunnel() {
  local A CA URL
  A="$(uname -m)"
  case "$A" in x86_64|amd64) CA="amd64" ;; aarch64|arm64) CA="arm64" ;; armv7l) CA="arm" ;; *) return 1 ;; esac
  mkdir -p "$INSTALL_DIR/bin"
  if [ ! -x "$INSTALL_DIR/bin/cloudflared" ]; then
    c "Downloading cloudflared ..."
    curl -fsSL "https://github.com/cloudflare/cloudflared/releases/latest/download/cloudflared-linux-$CA" -o "$INSTALL_DIR/bin/cloudflared" || return 1
    chmod +x "$INSTALL_DIR/bin/cloudflared"
  fi
  touch "$INSTALL_DIR/tunnel.enabled"
  write_helpers
  "$INSTALL_DIR/stop.sh" >/dev/null 2>&1
  rm -f "$INSTALL_DIR/tunnel.log"
  sleep 1
  "$INSTALL_DIR/start.sh"
  c "Opening a public tunnel (about 20 seconds) ..."
  URL=""
  for _ in $(seq 1 40); do
    URL="$(grep -o 'https://[a-z0-9-]*\\.trycloudflare\\.com' "$INSTALL_DIR/tunnel.log" 2>/dev/null | head -n1)"
    [ -n "$URL" ] && break
    sleep 1.5
  done
  [ -n "$URL" ] || return 1
  ENROLL_HOST="\${URL#https://}"; ENROLL_PORT="443"; ENROLL_SSL="true"; ENROLL_TUNNEL="true"
  c "Waiting for the tunnel address to go live (can take up to a minute) ..."
  for _ in $(seq 1 40); do
    [ "$(curl -s -m 5 -o /dev/null -w '%{http_code}' "$URL/" 2>/dev/null)" != "000" ] && break
    sleep 2
  done
  return 0
}

c "Registering with your panel ..."
DONE=0; TUNNELED=0
for attempt in 1 2 3 4 5; do
  enroll_call
  if [ "$CODE" = "200" ]; then DONE=1; break; fi
  warn "Attempt $attempt/5: \${MSG:-HTTP $CODE}"
  [ "$CODE" = "404" ] && break
  if [ "$TUNNELED" -eq 0 ] && [ "$CODE" = "400" ] && printf '%s' "$MSG" | grep -qi "could not reach"; then
    if [ "$HAS_SYSTEMD" -eq 0 ] || [ "$IS_ROOT" -eq 1 ]; then
      warn "The panel cannot reach this machine directly — switching to a public tunnel."
      TUNNELED=1
      if setup_tunnel; then continue; else warn "Could not open a tunnel."; fi
    fi
  fi
  sleep 8
done

echo
if [ "$DONE" -eq 1 ]; then
  NODE_ID="$(printf '%s' "$RESP" | sed '$d' | sed -n 's/.*"nodeId":"\\([^"]*\\)".*/\\1/p')"
  if [ -n "$NODE_ID" ]; then echo "NODE_ID=$NODE_ID" >> "$INSTALL_DIR/.env"; fi
  if [ "$TUNNELED" -eq 1 ] && [ -n "$NODE_ID" ]; then
    # restart the tunnel supervisor so it knows the node id and can re-announce a new address after restarts
    "$INSTALL_DIR/stop.sh" >/dev/null 2>&1; sleep 1; "$INSTALL_DIR/start.sh"
  fi
  if [ "$HAS_SYSTEMD" -eq 0 ]; then
    # come back automatically when the shell / container starts again
    for rc in "$HOME/.bashrc" "$HOME/.profile"; do
      [ -f "$rc" ] || continue
      grep -q "$INSTALL_DIR/start.sh" "$rc" 2>/dev/null || echo "[ -x \\"$INSTALL_DIR/start.sh\\" ] && \\"$INSTALL_DIR/start.sh\\" >/dev/null 2>&1" >> "$rc"
    done
    command -v crontab >/dev/null 2>&1 && ( crontab -l 2>/dev/null | grep -v "$INSTALL_DIR/start.sh"; echo "@reboot $INSTALL_DIR/start.sh >/dev/null 2>&1" ) | crontab - 2>/dev/null
  fi
  ok "Done! \\"$NODE_NAME\\" is now a node in your panel (Nodes page)."
  if [ "$HAS_SYSTEMD" -eq 1 ]; then
    echo "   • Game server ports you create must be open in this VPS's firewall / cloud security group."
    echo "   • Status:  systemctl status $SERVICE      Logs:  journalctl -u $SERVICE -f"
  else
    echo "   • No systemd here: start again with  $INSTALL_DIR/start.sh   stop with  $INSTALL_DIR/stop.sh   logs: $INSTALL_DIR/node.log"
    [ "$USE_DOCKER" -eq 0 ] && echo "   • Local mode: servers run as plain processes (install Java yourself for Minecraft)."
    [ "$TUNNELED" -eq 1 ] && echo "   • The panel reaches this node through a tunnel. Game ports are NOT public from here — for Minecraft use a TCP tunnel (e.g. playit.gg)."
  fi
else
  fail "The node is installed but could not register with the panel (\${MSG:-HTTP $CODE}). Open port $ENROLL_PORT/tcp on this machine (firewall + cloud security group) and run the same command again."
fi
exit 0
`;
}

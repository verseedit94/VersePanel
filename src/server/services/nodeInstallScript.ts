/**
 * Bash installer served to a new VPS by the panel (see routes/nodeEnroll.ts).
 * Every value interpolated into the script is validated/sanitised by the caller; only [A-Za-z0-9 ._:/@-] reach the shell.
 */
export interface ScriptInput {
  panelUrl: string;
  enrollToken: string;
  nodeToken: string;
  port: number;
  domain?: string;
  name: string;
}

const safe = (v: string) => String(v).replace(/[^A-Za-z0-9 ._:/@-]/g, "");

export function buildInstallScript(i: ScriptInput): string {
  const panel = safe(i.panelUrl);
  const name = safe(i.name) || "node";
  const domain = safe(i.domain || "");
  return `#!/usr/bin/env bash
# Verse Node installer — adds this VPS to your panel as "${name}".
# Generated by ${panel}. Safe to run again (it updates the node and keeps its servers).
set -o pipefail

PANEL_URL="${panel}"
ENROLL_TOKEN="${safe(i.enrollToken)}"
NODE_TOKEN="${safe(i.nodeToken)}"
NODE_PORT="${Number(i.port) || 6870}"
NODE_DOMAIN="${domain}"
NODE_NAME="${name}"
INSTALL_DIR="/opt/verse-node"
SERVICE="verse-node"

c() { printf '\\033[1;36m[verse-node]\\033[0m %s\\n' "$*"; }
ok() { printf '\\033[1;32m[ok]\\033[0m %s\\n' "$*"; }
warn() { printf '\\033[1;33m[warn]\\033[0m %s\\n' "$*"; }
fail() { printf '\\033[1;31m[error]\\033[0m %s\\n' "$*" >&2; exit 1; }

[ "$(id -u)" -eq 0 ] || fail "Run this as root:  curl -fsSL \\"$PANEL_URL/api/nodes/enroll/$ENROLL_TOKEN/install.sh\\" | sudo bash"
command -v systemctl >/dev/null 2>&1 || fail "This installer needs systemd (Ubuntu / Debian / CentOS / Rocky / AlmaLinux)."
[ "$(uname -s)" = "Linux" ] || fail "Linux only."

PM=""
if command -v apt-get >/dev/null 2>&1; then PM="apt"; elif command -v dnf >/dev/null 2>&1; then PM="dnf"; elif command -v yum >/dev/null 2>&1; then PM="yum"; fi
[ -n "$PM" ] || fail "Unsupported Linux (need apt, dnf or yum)."

pkg_install() {
  case "$PM" in
    apt) DEBIAN_FRONTEND=noninteractive apt-get install -y "$@" >/dev/null 2>&1 ;;
    dnf) dnf install -y "$@" >/dev/null 2>&1 ;;
    yum) yum install -y "$@" >/dev/null 2>&1 ;;
  esac
}

c "Installing node \\"$NODE_NAME\\" ..."
[ "$PM" = "apt" ] && apt-get update -y >/dev/null 2>&1
pkg_install curl ca-certificates tar gzip || true

# ---------- Node.js >= 20 ----------
NODE_OK=0
if command -v node >/dev/null 2>&1; then
  [ "$(node -v | tr -d v | cut -d. -f1)" -ge 20 ] && NODE_OK=1
fi
if [ "$NODE_OK" -eq 0 ]; then
  c "Installing Node.js 22 ..."
  if [ "$PM" = "apt" ]; then
    curl -fsSL https://deb.nodesource.com/setup_22.x | bash - >/dev/null 2>&1
  else
    curl -fsSL https://rpm.nodesource.com/setup_22.x | bash - >/dev/null 2>&1
  fi
  pkg_install nodejs
  command -v node >/dev/null 2>&1 || fail "Could not install Node.js."
fi
ok "Node.js $(node -v)"

# ---------- Docker ----------
if ! command -v docker >/dev/null 2>&1; then
  c "Installing Docker (takes a minute) ..."
  curl -fsSL https://get.docker.com | sh >/dev/null 2>&1 || fail "Docker installation failed."
fi
systemctl enable --now docker >/dev/null 2>&1 || true
docker info >/dev/null 2>&1 && ok "Docker is running" || warn "Docker is not answering yet — servers need it. Check: systemctl status docker"

# ---------- download the node ----------
c "Downloading node files from your panel ..."
TMP="$(mktemp /tmp/verse-node.XXXXXX.tgz)"
HTTP=$(curl -sS -o "$TMP" -w '%{http_code}' "$PANEL_URL/api/nodes/enroll/$ENROLL_TOKEN/package.tgz") || fail "Cannot reach the panel at $PANEL_URL from this VPS."
[ "$HTTP" = "200" ] || fail "Panel refused the download (HTTP $HTTP). The link may have expired — create a new one in Nodes → Add VPS."

systemctl stop "$SERVICE" >/dev/null 2>&1 || true
mkdir -p "$INSTALL_DIR"
tar -xzf "$TMP" -C "$INSTALL_DIR" || fail "Could not unpack the node files."
rm -f "$TMP"

c "Installing dependencies (this can take a few minutes) ..."
( cd "$INSTALL_DIR" && npm install --omit=dev --no-audit --no-fund --legacy-peer-deps >/tmp/verse-node-npm.log 2>&1 ) || { tail -n 15 /tmp/verse-node-npm.log; fail "npm install failed (log above)."; }
ok "Dependencies installed"

# ---------- config ----------
umask 077
cat > "$INSTALL_DIR/.env" <<ENVEOF
NODE_ENV=production
NODE_MODE=true
NODE_TOKEN=$NODE_TOKEN
PORT=$NODE_PORT
ENVEOF
umask 022

cat > "/etc/systemd/system/$SERVICE.service" <<UNITEOF
[Unit]
Description=Verse Node ($NODE_NAME)
After=network-online.target docker.service
Wants=network-online.target

[Service]
WorkingDirectory=$INSTALL_DIR
EnvironmentFile=$INSTALL_DIR/.env
ExecStart=$(command -v node) dist/server.cjs
Restart=always
RestartSec=5
User=root

[Install]
WantedBy=multi-user.target
UNITEOF

systemctl daemon-reload
systemctl enable "$SERVICE" >/dev/null 2>&1
systemctl restart "$SERVICE"

c "Waiting for the node to start ..."
UP=0
for _ in $(seq 1 40); do
  if curl -fs "http://127.0.0.1:$NODE_PORT/" >/dev/null 2>&1; then UP=1; break; fi
  sleep 1.5
done
[ "$UP" -eq 1 ] || { journalctl -u "$SERVICE" -n 25 --no-pager; fail "The node did not start (log above)."; }
ok "Node is running on port $NODE_PORT"

# ---------- firewall ----------
if command -v ufw >/dev/null 2>&1 && ufw status 2>/dev/null | grep -q "Status: active"; then
  ufw allow "$NODE_PORT/tcp" >/dev/null 2>&1 && ok "ufw: opened $NODE_PORT/tcp"
fi

# ---------- public address / optional HTTPS ----------
PUBLIC_IP=""
for u in https://api.ipify.org https://ifconfig.me/ip https://icanhazip.com; do
  PUBLIC_IP="$(curl -fs -m 5 "$u" 2>/dev/null | tr -d '[:space:]')"
  case "$PUBLIC_IP" in [0-9]*.[0-9]*.[0-9]*.[0-9]*) break ;; *) PUBLIC_IP="" ;; esac
done

ENROLL_PORT="$NODE_PORT"
ENROLL_SSL="false"
ENROLL_HOST="$PUBLIC_IP"

if [ -n "$NODE_DOMAIN" ]; then
  c "Checking DNS for $NODE_DOMAIN ..."
  RESOLVED="$(getent ahostsv4 "$NODE_DOMAIN" 2>/dev/null | awk '{print $1}' | sort -u | tr '\\n' ' ')"
  if [ -n "$PUBLIC_IP" ] && echo " $RESOLVED " | grep -q " $PUBLIC_IP "; then
    ok "$NODE_DOMAIN points to this VPS ($PUBLIC_IP)"
    if ! command -v caddy >/dev/null 2>&1; then
      c "Installing Caddy for HTTPS ..."
      if [ "$PM" = "apt" ]; then
        pkg_install debian-keyring debian-archive-keyring apt-transport-https gpg
        curl -1sLf 'https://dl.cloudsmith.io/public/caddy/stable/gpg.key' | gpg --dearmor --yes -o /usr/share/keyrings/caddy-stable-archive-keyring.gpg
        curl -1sLf 'https://dl.cloudsmith.io/public/caddy/stable/debian.deb.txt' > /etc/apt/sources.list.d/caddy-stable.list
        apt-get update -y >/dev/null 2>&1; pkg_install caddy
      else
        dnf install -y 'dnf-command(copr)' >/dev/null 2>&1 && dnf copr enable -y @caddy/caddy >/dev/null 2>&1 && pkg_install caddy
      fi
    fi
    if command -v caddy >/dev/null 2>&1; then
      mkdir -p /etc/caddy
      printf '%s {\\n    reverse_proxy 127.0.0.1:%s\\n}\\n' "$NODE_DOMAIN" "$NODE_PORT" > /etc/caddy/Caddyfile
      systemctl enable --now caddy >/dev/null 2>&1; systemctl reload caddy >/dev/null 2>&1 || systemctl restart caddy >/dev/null 2>&1
      command -v ufw >/dev/null 2>&1 && ufw status 2>/dev/null | grep -q "Status: active" && { ufw allow 80/tcp >/dev/null 2>&1; ufw allow 443/tcp >/dev/null 2>&1; }
      ENROLL_PORT="443"; ENROLL_SSL="true"; ENROLL_HOST="$NODE_DOMAIN"
      ok "HTTPS is set up on https://$NODE_DOMAIN"
    else
      warn "Could not install Caddy — continuing without HTTPS (plain http on port $NODE_PORT)."
    fi
  else
    warn "$NODE_DOMAIN does not point to this VPS (\${RESOLVED:-no A record}; this VPS is \${PUBLIC_IP:-unknown}). Continuing without HTTPS."
    warn "Fix the A record later and run this command again to enable HTTPS."
  fi
fi

# ---------- tell the panel ----------
c "Registering with your panel ..."
BODY=$(printf '{"port":%s,"ssl":%s,"host":"%s"}' "$ENROLL_PORT" "$ENROLL_SSL" "$ENROLL_HOST")
DONE=0
for attempt in 1 2 3; do
  RESP="$(curl -sS -m 40 -X POST -H 'Content-Type: application/json' -d "$BODY" -w '\\n%{http_code}' "$PANEL_URL/api/nodes/enroll/$ENROLL_TOKEN" 2>&1)"
  CODE="$(printf '%s' "$RESP" | tail -n1)"
  if [ "$CODE" = "200" ]; then DONE=1; break; fi
  MSG="$(printf '%s' "$RESP" | sed '$d' | sed -n 's/.*"error":"\\([^"]*\\)".*/\\1/p')"
  warn "Attempt $attempt/3: \${MSG:-HTTP $CODE}"
  [ "$CODE" = "404" ] && break
  sleep 6
done

echo
if [ "$DONE" -eq 1 ]; then
  ok "Done! \\"$NODE_NAME\\" is now a node in your panel (Nodes page)."
  echo "   • Game server ports you create must be open in this VPS's firewall / cloud security group."
  echo "   • Status:  systemctl status $SERVICE      Logs:  journalctl -u $SERVICE -f"
else
  fail "The node is installed but could not register with the panel. Open port $ENROLL_PORT/tcp on this VPS (firewall + cloud security group) and run the same command again."
fi
`;
}

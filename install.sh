ask_domain() {
    # Non-interactive: PANEL_DOMAIN env var may be preset (still verified).
    local DOMAIN_RE='^([a-zA-Z0-9]([a-zA-Z0-9-]{0,61}[a-zA-Z0-9])?\.)+[a-zA-Z]{2,63}$'
    local SERVER_IP
    SERVER_IP=$(get_public_ip) || SERVER_IP=""

    if [ ! -t 0 ] && [ -z "$PANEL_DOMAIN_PRESET" ]; then
        return 0
    fi

    print_banner
    echo -e "╔══════════════════════════════════════════════╗"
    echo -e "║                PANEL DOMAIN                  ║"
    echo -e "╚══════════════════════════════════════════════╝"
    echo -e " Servers will be shown as ${GREEN}domain:port${NC} and the panel will open on your domain."
    echo -e " Create an ${YELLOW}A record${NC} for your domain pointing to: ${GREEN}${SERVER_IP:-YOUR_SERVER_IP}${NC}"
    echo -e " (If you use Cloudflare, turn the orange cloud OFF.)"
    echo ""

    local D="$PANEL_DOMAIN_PRESET"
    while true; do
        if [ -z "$D" ]; then
            read -p " Domain (e.g. panel.example.com) — Enter to skip: " D
        fi
        D=$(echo "$D" | tr 'A-Z' 'a-z' | sed 's#^https\?://##; s#/.*$##')
        if [ -z "$D" ]; then
            log_warning "No domain set. The panel will be reachable on http://${SERVER_IP:-SERVER_IP}:6767 (you can add a domain later in Admin Settings)."
            return 0
        fi
        if ! [[ "$D" =~ $DOMAIN_RE ]]; then
            log_error "'$D' is not a valid domain."; D=""; continue
        fi
        if [ -z "$SERVER_IP" ]; then
            log_warning "Could not detect this server's public IP, so DNS can't be verified automatically."
            read -p " Use '$D' anyway? (y/N): " ANS
            if [[ "$ANS" =~ ^[Yy]$ ]]; then PANEL_DOMAIN="$D"; return 0; fi
            D=""; continue
        fi

        log_info "Checking DNS for $D ..."
        local RESOLVED
        RESOLVED=$(resolve_domain_a "$D" | tr '\n' ' ')
        if echo " $RESOLVED " | grep -q " $SERVER_IP "; then
            log_success "$D → $SERVER_IP ✓ DNS is correct."
            PANEL_DOMAIN="$D"
            return 0
        fi
        if [ -z "$RESOLVED" ]; then
            log_error "No A record found for $D."
        else
            log_error "$D points to ${RESOLVED}but this server is $SERVER_IP."
        fi
        echo -e " Fix the A record (it can take a few minutes), then:"
        read -p " [r] retry   [n] enter another domain   [s] skip domain: " ANS
        case "$ANS" in
            n|N) D="" ;;
            s|S) log_warning "Skipping domain setup."; return 0 ;;
            *) ;;   # retry same domain
        esac
    done
}

apply_domain_settings() {
    mkdir -p .data
    PANEL_MODE="$PANEL_MODE" PANEL_DOMAIN="$PANEL_DOMAIN" PANEL_SCHEME="$PANEL_SCHEME" LOCAL_IP="$LOCAL_IP" node -e '
      const fs=require("fs");const f=".data/settings.json";
      let s={};try{s=JSON.parse(fs.readFileSync(f,"utf8"))}catch{}
      s.accessMode=process.env.PANEL_MODE==="domain"?"domain":"local";
      if(s.accessMode==="domain"&&process.env.PANEL_DOMAIN){
        s.panelDomain=process.env.PANEL_DOMAIN;s.domainVerified=true;s.panelScheme=process.env.PANEL_SCHEME;
        delete s.localIp;
      } else {
        delete s.panelDomain;delete s.domainVerified;
        if(process.env.LOCAL_IP)s.localIp=process.env.LOCAL_IP;
      }
      fs.writeFileSync(f,JSON.stringify(s,null,2));
    '
    if [ -n "$PANEL_DOMAIN" ]; then
        grep -q '^PANEL_DOMAIN=' .env 2>/dev/null && sed -i "s#^PANEL_DOMAIN=.*#PANEL_DOMAIN=${PANEL_DOMAIN}#" .env || echo "PANEL_DOMAIN=${PANEL_DOMAIN}" >> .env
    fi
}

setup_caddy() {
    [ -z "$PANEL_DOMAIN" ] && return 0
    if ss -lnt 2>/dev/null | grep -E ':(80|443) ' | grep -vq caddy; then
        if ! command -v caddy >/dev/null 2>&1; then
            log_warning "Ports 80/443 are already in use by another service. Skipping automatic HTTPS."
            log_warning "Point your own reverse proxy at http://127.0.0.1:6767 for ${PANEL_DOMAIN}."
            return 1
        fi
    fi
    if ! command -v caddy >/dev/null 2>&1; then
        log_info "Installing Caddy (automatic HTTPS reverse proxy)..."
        if command -v apt-get >/dev/null 2>&1; then
            sudo apt-get install -y debian-keyring debian-archive-keyring apt-transport-https curl gpg >/dev/null 2>&1
            curl -1sLf 'https://dl.cloudsmith.io/public/caddy/stable/gpg.key' | sudo gpg --dearmor --yes -o /usr/share/keyrings/caddy-stable-archive-keyring.gpg
            curl -1sLf 'https://dl.cloudsmith.io/public/caddy/stable/debian.deb.txt' | sudo tee /etc/apt/sources.list.d/caddy-stable.list >/dev/null
            sudo apt-get update -y >/dev/null 2>&1
            sudo apt-get install -y caddy >/dev/null 2>&1
        elif command -v dnf >/dev/null 2>&1; then
            sudo dnf install -y 'dnf-command(copr)' >/dev/null 2>&1 && sudo dnf copr enable -y @caddy/caddy >/dev/null 2>&1 && sudo dnf install -y caddy >/dev/null 2>&1
        fi
    fi
    if ! command -v caddy >/dev/null 2>&1; then
        log_warning "Could not install Caddy automatically. Panel is on http://${PANEL_DOMAIN}:6767 — set up a reverse proxy manually for HTTPS."
        return 1
    fi
    sudo mkdir -p /etc/caddy
    printf '%s {\n    encode gzip\n    reverse_proxy 127.0.0.1:6767\n}\n' "$PANEL_DOMAIN" | sudo tee /etc/caddy/Caddyfile >/dev/null
    sudo systemctl enable --now caddy >/dev/null 2>&1 || true
    sudo systemctl reload caddy >/dev/null 2>&1 || sudo systemctl restart caddy >/dev/null 2>&1 || true
    PANEL_SCHEME="https"
    # panel keeps running on 6767 behind Caddy; record https as the public scheme
    apply_domain_settings
    return 0
}


#  Domain setup (asked at install time, like Pterodactyl)
# ─────────────────────────────────────────────────────────────
PANEL_DOMAIN=""
PANEL_SCHEME="http"
PANEL_MODE="local"      # "domain" or "local"
LOCAL_IP=""

get_public_ip() {
    local ip=""
    for u in https://api.ipify.org https://ifconfig.me/ip https://icanhazip.com; do
        ip=$(curl -s -m 5 "$u" 2>/dev/null | tr -d '[:space:]')
        if [[ "$ip" =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}$ ]]; then echo "$ip"; return 0; fi
    done
    return 1
}

resolve_domain_a() {
    local d=$1
    if command -v dig >/dev/null 2>&1; then
        dig +short A "$d" @1.1.1.1 2>/dev/null | grep -E '^[0-9]+(\.[0-9]+){3}$'
    else
        getent ahostsv4 "$d" 2>/dev/null | awk '{print $1}' | sort -u
    fi
}

detect_local_ip() {
    local ip=""
    ip=$(ip -4 route get 1.1.1.1 2>/dev/null | awk '{for(i=1;i<=NF;i++) if($i=="src"){print $(i+1); exit}}')
    if [ -z "$ip" ]; then
        ip=$(hostname -I 2>/dev/null | tr ' ' '\n' | grep -E '^(192\.168\.|10\.|172\.(1[6-9]|2[0-9]|3[0-1])\.)' | head -n1)
    fi
    if [ -z "$ip" ]; then
        ip=$(ip -4 addr show wlan0 2>/dev/null | awk '/inet /{sub(/\/.*/,"",$2); print $2; exit}')
    fi
    if [ -z "$ip" ]; then
        ip=$(ifconfig 2>/dev/null | awk '/inet /{print $2}' | sed 's/addr://' | grep -v '^127\.' | head -n1)
    fi
    [ -z "$ip" ] && ip="127.0.0.1"
    echo "$ip"
}

ask_local_ip() {
    local DETECTED
    DETECTED=$(detect_local_ip)
    LOCAL_IP="$DETECTED"
    if [ -t 0 ]; then
        echo ""
        log_info "Detected local IP: ${DETECTED}"
        if [ "$DETECTED" = "127.0.0.1" ]; then
            log_warning "Could not find a network IP (is Wi-Fi / network on?). Other devices won't reach the panel until you connect."
        fi
        read -p " Press Enter to use ${DETECTED}, or type another IP: " ANS
        if [[ "$ANS" =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}$ ]]; then LOCAL_IP="$ANS"; fi
    fi
    log_success "Panel will run on http://${LOCAL_IP}:6767 (local network)."
}

